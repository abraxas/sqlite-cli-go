LABEL = "sqlite-cli-go"
WITNESS = "SQLITE-CLI-GO-WITNESS"
COMPOSE_PROJECT = os.environ.get("COMPOSE_PROJECT_NAME", LABEL)
HERE = Path(__file__).resolve().parent
SERVICE = "cli"
SQLITE_BIN = "sqlite3"
PIN_VERSION = "3.53.4"
PIN_SOURCE_ID = "bf7c7f30031888f4e796e429ab3978879485813aaca6f641c7b33e4e09459bcc"
SAFE_BLOCK = "cannot run .shell in safe mode"
EXEC_TIMEOUT_S = 30

# Unterminated SELECT, then SQL Server go or Oracle /, then a later dot-command.
# .shell echo TOKEN is the oracle, not a payload.
SCRIPT_GO = f"select 1\ngo\n.shell echo {WITNESS}\n"
SCRIPT_SLASH = f"select 1\n/\n.shell echo {WITNESS}\n"


@dataclass(frozen=True)
class ShellRun:
    name: str
    argv: tuple[str, ...]
    returncode: int
    stdout: str
    stderr: str

    @property
    def combined(self) -> str:
        return f"{self.stdout}\n{self.stderr}"

    def has_witness(self) -> bool:
        return WITNESS in self.stdout or WITNESS in self.stderr

    def has_safe_block(self) -> bool:
        return SAFE_BLOCK in self.stderr or SAFE_BLOCK in self.stdout


def log(msg: str) -> None:
    print(msg, flush=True)


def fail(reason: str) -> int:
    log(f"FAIL {LABEL} {reason} {WITNESS}")
    return 1


def compose(*args: str, timeout: int = 60) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["docker", "compose", "-p", COMPOSE_PROJECT, *args],
        cwd=HERE,
        text=True,
        capture_output=True,
        timeout=timeout,
    )


def run_sqlite(name: str, script: str, extra_args: list[str] | None = None) -> ShellRun:
    argv = [
        "docker",
        "compose",
        "-p",
        COMPOSE_PROJECT,
        "exec",
        "-T",
        SERVICE,
        SQLITE_BIN,
        *(extra_args or []),
    ]
    proc = subprocess.run(
        argv,
        cwd=HERE,
        input=script,
        text=True,
        capture_output=True,
        timeout=EXEC_TIMEOUT_S,
        check=False,
    )
    return ShellRun(
        name=name,
        argv=tuple(argv[argv.index(SQLITE_BIN) :]),
        returncode=proc.returncode,
        stdout=proc.stdout or "",
        stderr=proc.stderr or "",
    )


def oneline(text: str, limit: int = 240) -> str:
    collapsed = text.replace("\r\n", "\\n").replace("\n", "\\n")
    if len(collapsed) > limit:
        return collapsed[:limit] + "..."
    return collapsed


def summarize(run: ShellRun) -> None:
    log(
        f"{run.name} argv={list(run.argv)!r} rc={run.returncode} "
        f"witness={int(run.has_witness())} safe-block={int(run.has_safe_block())} "
        f"stdout={oneline(run.stdout)!r} stderr={oneline(run.stderr)!r}"
    )


def sqlite_version() -> str:
    proc = compose("exec", "-T", SERVICE, SQLITE_BIN, "--version", timeout=30)
    blob = (proc.stdout or proc.stderr or "").strip()
    log(f"sqlite-version rc={proc.returncode} value={oneline(blob, 200)!r}")
    return blob


def main() -> int:
    log(f"label={LABEL} compose={COMPOSE_PROJECT} loopback=127.0.0.1:18920")
    version = sqlite_version()
    if PIN_VERSION not in version:
        return fail(f"bad-version={oneline(version, 120)}")
    if PIN_SOURCE_ID not in version:
        return fail(f"bad-source-id={oneline(version, 120)}")

    log("== go terminator then .shell (no --safe) ==")
    go_run = run_sqlite("go", SCRIPT_GO)
    summarize(go_run)

    log("== slash terminator then .shell (no --safe) ==")
    slash_run = run_sqlite("slash", SCRIPT_SLASH)
    summarize(slash_run)

    log("== go terminator then .shell with --safe ==")
    safe_go = run_sqlite("safe-go", SCRIPT_GO, extra_args=["--safe"])
    summarize(safe_go)

    log("== slash terminator then .shell with --safe ==")
    safe_slash = run_sqlite("safe-slash", SCRIPT_SLASH, extra_args=["--safe"])
    summarize(safe_slash)

    if not go_run.has_witness():
        return fail("go-did-not-run-shell")
    if not slash_run.has_witness():
        return fail("slash-did-not-run-shell")
    if safe_go.has_witness():
        return fail("safe-go-ran-shell")
    if safe_slash.has_witness():
        return fail("safe-slash-ran-shell")
    if not safe_go.has_safe_block():
        return fail("safe-go-no-block")
    if not safe_slash.has_safe_block():
        return fail("safe-slash-no-block")

    log(
        f"SUCCESS {LABEL} how=go-then-dot-shell slash=yes safe=blocked "
        f"{WITNESS}"
    )
    return 0


